"""Write the ruff ``banned-api`` table that ``scripts/banned.toml`` generates, or check that it is up to date.

``scripts/banned.toml`` lists the libraries that the project replaces. The table in ``pyproject.toml`` between a begin
and an end marker bans the imports of each replaced library.

Run ``uv run python -m scripts.sync_banned`` to write the table, and ``--check`` to fail when it is out of date. The
``sync-banned`` hook runs the check.
"""

import sys
import tomllib
from collections.abc import Sequence
from pathlib import Path

import attrs

ROOT = Path(__file__).resolve().parent.parent
BANNED = ROOT / "scripts" / "banned.toml"
PYPROJECT = ROOT / "pyproject.toml"
RUFF_BEGIN = "# BEGIN banned-api: generated by scripts/sync_banned.py from scripts/banned.toml. Do not edit by hand.\n"
RUFF_END = "# END banned-api\n"
CHECK_FLAG = "--check"


@attrs.frozen
class Ban:
    """The part of one library choice of ``scripts/banned.toml`` that the guards read.

    Attributes
    ----------
    use: str
        The library that the project uses.
    imports: tuple[str, ...]
        The modules that ruff bans.
    dependencies: tuple[str, ...]
        The distribution names that ``scripts/check_dependencies.py`` bans.
    files: tuple[str, ...]
        The file globs that ``scripts/check_layout.py`` bans.

    """

    use: str
    imports: tuple[str, ...] = ()
    dependencies: tuple[str, ...] = ()
    files: tuple[str, ...] = ()


def load_bans(text: str) -> list[Ban]:
    """Parse the content of ``scripts/banned.toml``.

    Parameters
    ----------
    text: str
        The content of the file.

    Returns
    -------
    list[Ban]
        The library choices, in the order of the file.

    """
    return [
        Ban(
            use=entry["use"],
            imports=tuple(entry.get("imports", ())),
            dependencies=tuple(entry.get("dependencies", ())),
            files=tuple(entry.get("files", ())),
        )
        for entry in tomllib.loads(text)["ban"]
    ]


def ruff_table(bans: Sequence[Ban]) -> str:
    """Write the ruff ``banned-api`` table.

    Parameters
    ----------
    bans: Sequence[Ban]
        The library choices.

    Returns
    -------
    str
        The TOML table, with one line for each banned module, sorted by module.

    """
    messages = {module: f"Use {ban.use}. See .claude/rules/libraries.md." for ban in bans for module in ban.imports}
    lines = [f'"{module}".msg = "{messages[module]}"' for module in sorted(messages)]
    return "[tool.ruff.lint.flake8-tidy-imports.banned-api]\n" + "".join(f"{line}\n" for line in lines)


def replace_between(text: str, begin: str, end: str, body: str) -> str:
    """Replace the text between two marker lines.

    Parameters
    ----------
    text: str
        The content of the file.
    begin: str
        The begin marker line.
    end: str
        The end marker line.
    body: str
        The new text between the markers.

    Returns
    -------
    str
        The content with the new text. The markers stay.

    Raises
    ------
    MarkerError
        If the file lacks one of the markers.

    """
    head, found, rest = text.partition(begin)
    _, found_end, tail = rest.partition(end)
    if not found or not found_end:
        raise MarkerError(begin)
    return head + begin + body + end + tail


class MarkerError(LookupError):
    """A file lacks the markers of a generated table."""

    def __init__(self, marker: str) -> None:
        """Build the message from the missing marker.

        Parameters
        ----------
        marker: str
            The begin marker of the table.

        """
        super().__init__(f"the file lacks the marker lines of the generated table: {marker.strip()}")


def main(argv: Sequence[str] = ()) -> int:
    """Write the generated table, or check it with ``--check``.

    Parameters
    ----------
    argv: Sequence[str]
        ``--check`` to check the table without a change.

    Returns
    -------
    int
        The process exit code: 1 if ``--check`` finds the table out of date, 0 otherwise.

    """
    bans = load_bans(BANNED.read_text(encoding="utf-8"))
    text = PYPROJECT.read_text(encoding="utf-8")
    new = replace_between(text, RUFF_BEGIN, RUFF_END, ruff_table(bans))
    if new == text:
        return 0
    if CHECK_FLAG in argv:
        sys.stderr.write("out of date: pyproject.toml. Run `uv run python -m scripts.sync_banned`.\n")
        return 1
    PYPROJECT.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
