"""Write the tables that ``scripts/banned.toml`` generates, or check that they are up to date.

``scripts/banned.toml`` lists the libraries that the project replaces. Two files hold a table generated from it, each
between a begin and an end marker:

- ``pyproject.toml``: the ruff ``banned-api`` table, which bans the imports of each replaced library.
- ``.claude/rules/libraries.md``: the table of the library choices, with the reason and the guard of each one.

Run ``uv run python -m scripts.sync_banned`` to write both tables, and ``--check`` to fail when one is out of date. The
``sync-banned`` hook runs the check.
"""

import sys
import tomllib
from collections.abc import Sequence
from pathlib import Path

import attrs

ROOT = Path(__file__).resolve().parent.parent
BANNED = ROOT / "scripts" / "banned.toml"
PYPROJECT = ROOT / "pyproject.toml"
RULE = ROOT / ".claude" / "rules" / "libraries.md"
RUFF_BEGIN = "# BEGIN banned-api: generated by scripts/sync_banned.py from scripts/banned.toml. Do not edit by hand.\n"
RUFF_END = "# END banned-api\n"
RULE_BEGIN = (
    "<!-- BEGIN banned: generated by scripts/sync_banned.py from scripts/banned.toml. Do not edit by hand. -->\n"
)
RULE_END = "<!-- END banned -->\n"
CHECK_FLAG = "--check"


@attrs.frozen
class Ban:
    """One library choice of ``scripts/banned.toml``.

    Attributes
    ----------
    need: str
        What the project needs the library for.
    use: str
        The library that the project uses.
    instead_of: str
        The libraries that the project does not use.
    reason: str
        Why the project uses ``use``.
    imports: tuple[str, ...]
        The modules that ruff bans.
    dependencies: tuple[str, ...]
        The distribution names that ``scripts/check_dependencies.py`` bans.
    files: tuple[str, ...]
        The file globs that ``scripts/check_layout.py`` bans.
    guard: str
        A guard that is not one of the three above, or an empty string.

    """

    need: str
    use: str
    instead_of: str
    reason: str
    imports: tuple[str, ...] = ()
    dependencies: tuple[str, ...] = ()
    files: tuple[str, ...] = ()
    guard: str = ""


def load_bans(text: str) -> list[Ban]:
    """Parse the content of ``scripts/banned.toml``.

    Parameters
    ----------
    text: str
        The content of the file.

    Returns
    -------
    list[Ban]
        The library choices, in the order of the file.

    """
    return [
        Ban(
            need=entry["need"],
            use=entry["use"],
            instead_of=entry["instead_of"],
            reason=entry["reason"],
            imports=tuple(entry.get("imports", ())),
            dependencies=tuple(entry.get("dependencies", ())),
            files=tuple(entry.get("files", ())),
            guard=entry.get("guard", ""),
        )
        for entry in tomllib.loads(text)["ban"]
    ]


def guards(ban: Ban) -> str:
    """Describe the guards of one library choice for the table of the rule.

    Parameters
    ----------
    ban: Ban
        The library choice.

    Returns
    -------
    str
        The guards, separated by semicolons.

    """
    parts = []
    if ban.imports:
        parts.append("Import ban: " + ", ".join(f"`{module}`" for module in ban.imports))
    if ban.dependencies:
        parts.append("Dependency ban: " + ", ".join(f"`{name}`" for name in ban.dependencies))
    if ban.files:
        parts.append("File ban: " + ", ".join(f"`{glob}`" for glob in ban.files))
    if ban.guard:
        parts.append(ban.guard)
    return "; ".join(parts)


def ruff_table(bans: Sequence[Ban]) -> str:
    """Write the ruff ``banned-api`` table.

    Parameters
    ----------
    bans: Sequence[Ban]
        The library choices.

    Returns
    -------
    str
        The TOML table, with one line for each banned module, sorted by module.

    """
    messages = {module: f"Use {ban.use}. See .claude/rules/libraries.md." for ban in bans for module in ban.imports}
    lines = [f'"{module}".msg = "{messages[module]}"' for module in sorted(messages)]
    return "[tool.ruff.lint.flake8-tidy-imports.banned-api]\n" + "".join(f"{line}\n" for line in lines)


def rule_table(bans: Sequence[Ban]) -> str:
    """Write the Markdown table of the library choices.

    Parameters
    ----------
    bans: Sequence[Ban]
        The library choices.

    Returns
    -------
    str
        The table, with one row for each choice.

    """
    rows = [f"| {ban.need} | {ban.use} | {ban.instead_of} | {ban.reason} | {guards(ban)} |\n" for ban in bans]
    return "| Need | Use | Not | Reason | Guard |\n| --- | --- | --- | --- | --- |\n" + "".join(rows)


def replace_between(text: str, begin: str, end: str, body: str) -> str:
    """Replace the text between two marker lines.

    Parameters
    ----------
    text: str
        The content of the file.
    begin: str
        The begin marker line.
    end: str
        The end marker line.
    body: str
        The new text between the markers.

    Returns
    -------
    str
        The content with the new text. The markers stay.

    Raises
    ------
    MarkerError
        If the file lacks one of the markers.

    """
    head, found, rest = text.partition(begin)
    _, found_end, tail = rest.partition(end)
    if not found or not found_end:
        raise MarkerError(begin)
    return head + begin + body + end + tail


class MarkerError(LookupError):
    """A file lacks the markers of a generated table."""

    def __init__(self, marker: str) -> None:
        """Build the message from the missing marker.

        Parameters
        ----------
        marker: str
            The begin marker of the table.

        """
        super().__init__(f"the file lacks the marker lines of the generated table: {marker.strip()}")


def main(argv: Sequence[str] = ()) -> int:
    """Write the generated tables, or check them with ``--check``.

    Parameters
    ----------
    argv: Sequence[str]
        ``--check`` to check the tables without a change.

    Returns
    -------
    int
        The process exit code: 1 if ``--check`` finds a table that is out of date, 0 otherwise.

    """
    bans = load_bans(BANNED.read_text(encoding="utf-8"))
    stale = []
    for path, begin, end, body in (
        (PYPROJECT, RUFF_BEGIN, RUFF_END, ruff_table(bans)),
        (RULE, RULE_BEGIN, RULE_END, rule_table(bans)),
    ):
        text = path.read_text(encoding="utf-8")
        new = replace_between(text, begin, end, body)
        if new == text:
            continue
        stale.append(path)
        if CHECK_FLAG not in argv:
            path.write_text(new, encoding="utf-8")
    if stale and CHECK_FLAG in argv:
        names = ", ".join(str(path.relative_to(ROOT)) for path in stale)
        sys.stderr.write(f"out of date: {names}. Run `uv run python -m scripts.sync_banned`.\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
