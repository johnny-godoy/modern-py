"""Write the tables that template/scripts/banned.toml generates into the template and the docs.

A rendered project checks its ruff table with `scripts.sync_banned --check`, so the template must ship it up to date.
The script renders the library answer set, runs `scripts.sync_banned` there, and copies the ruff table back into
`template/pyproject.toml.jinja`. It also writes the table of the library choices into `docs/libraries.md` for people
to read. The rendered projects hold no copy of that table: their rule file points at the configuration. Run the script
after each change of `template/scripts/banned.toml`: `just sync-tables`. With `--check`, it changes nothing and fails on
a stale table.
"""

import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs" / "libraries.md"
DOCS_BEGIN = "<!-- BEGIN banned: generated by scripts/sync_tables.py from template/scripts/banned.toml. Do not edit by hand. -->\n"
DOCS_END = "<!-- END banned -->\n"


def guards(entry: dict) -> str:
    """Describe the guards of one library choice for the table of the docs."""
    parts = []
    if entry.get("imports"):
        parts.append("Import ban: " + ", ".join(f"`{module}`" for module in entry["imports"]))
    if entry.get("dependencies"):
        parts.append("Dependency ban: " + ", ".join(f"`{name}`" for name in entry["dependencies"]))
    if entry.get("files"):
        parts.append("File ban: " + ", ".join(f"`{glob}`" for glob in entry["files"]))
    if entry.get("guard"):
        parts.append(entry["guard"])
    return "; ".join(parts)


def docs_table(entries: list) -> str:
    """Write the Markdown table of the library choices."""
    rows = [
        f"| {entry['need']} | {entry['use']} | {entry['instead_of']} | {entry['reason']} | {guards(entry)} |\n"
        for entry in entries
    ]
    return "| Need | Use | Not | Reason | Guard |\n| --- | --- | --- | --- | --- |\n" + "".join(rows)


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    with tempfile.TemporaryDirectory() as tmp:
        project = Path(tmp) / "library"
        subprocess.run([ROOT / "scripts" / "render.sh", "library", project, "--no-checks"], check=True)
        subprocess.run(["uv", "run", "--frozen", "python", "-m", "scripts.sync_banned"], cwd=project, check=True)
        sys.path.insert(0, str(project))
        from scripts import sync_banned  # the module of the rendered project

        ruff = (project / "pyproject.toml").read_text(encoding="utf-8")
        ruff_body = ruff.split(sync_banned.RUFF_BEGIN, 1)[1].split(sync_banned.RUFF_END, 1)[0]
        entries = tomllib.loads((ROOT / "template" / "scripts" / "banned.toml").read_text(encoding="utf-8"))["ban"]
        for path, begin, end, body in (
            (ROOT / "template" / "pyproject.toml.jinja", sync_banned.RUFF_BEGIN, sync_banned.RUFF_END, ruff_body),
            (DOCS, DOCS_BEGIN, DOCS_END, docs_table(entries)),
        ):
            text = path.read_text(encoding="utf-8")
            new = sync_banned.replace_between(text, begin, end, body)
            if new != text:
                stale.append(str(path.relative_to(ROOT)))
                if not check:
                    path.write_text(new, encoding="utf-8")
    if check and stale:
        sys.stderr.write(f"out of date: {', '.join(stale)}. Run `just sync-tables`.\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
